  // buyer
  const bp = await (await b.newContext({ viewport: { width: 1280, height: 860 } })).newPage();
  await bp.goto('http://localhost:5173/pay/' + m[1]); await bp.waitForTimeout(2000);
  await bp.screenshot({ path: `${OUT}/b-checkout.png`, fullPage: true });
  await bp.getByLabel('Card number').fill('4242424242424242');
  await bp.getByLabel('Expiry month').fill('12');
  await bp.getByLabel('Expiry year').fill('2030');
  await bp.getByLabel('CVV').fill('123');
  await bp.screenshot({ path: `${OUT}/b-checkout-filled.png`, fullPage: true });
  await bp.locator('form button[type=submit]').click();
  await bp.waitForTimeout(4000);
  await bp.screenshot({ path: `${OUT}/b-checkout-done.png`, fullPage: true });
  await bp.goto('http://localhost:5173/pay/doesnotexist'); await bp.waitForTimeout(1500);
  await bp.screenshot({ path: `${OUT}/b-checkout-bad.png` });
