  await ap.waitForTimeout(2000);
  await ap.screenshot({ path: `${OUT}/a-otp.png` });
  const acode = await ap.locator('code').first().textContent({ timeout: 10000 });
  await ap.locator('input').first().fill(acode.trim());
  await ap.locator('form button[type=submit]').first().click();
  await ap.waitForTimeout(3000);
  await ap.screenshot({ path: `${OUT}/a-merchants.png` });
  await ap.goto('http://localhost:5174/merchants/' + MID); await ap.waitForTimeout(2500);
  await ap.screenshot({ path: `${OUT}/a-merchant.png`, fullPage: true });
  await ap.goto('http://localhost:5174/settlement'); await ap.waitForTimeout(2500);
  await ap.screenshot({ path: `${OUT}/a-settlement.png` });
  await b.close();
